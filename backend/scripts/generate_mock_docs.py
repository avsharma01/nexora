def summary_docs(db: Session, company_id: int, name: str) -> dict[str, str]:
    """Numbers-only summary for a company WITHOUT a fake narrative (e.g. real data).

    States the latest month and the last 12 months per metric. It deliberately
    gives no reasons: a "why" question then honestly gets "the data does not
    explain the cause" until real documents are added.
    """
    latest = data_access.latest_date(db, company_id)
    if latest is None:
        return {}
    end = Period("month", latest.year, latest.month)
    start = months_back(end, 11)
    lines = [
        f"# {name}: KPI data summary",
        "",
        "> Auto-generated by backend/scripts/generate_mock_docs.py --all from the NEXORA KPI data. "
        "It contains figures only, no explanations.",
        "",
    ]
    for metric in data_access.available_metrics(db, company_id):
        series = data_access.get_series(db, company_id, metric)
        latest_fact = value_at(series, end, metric=metric)
        month_change = compare_periods(series, previous_period(end), end, metric=metric)
        year_trend = trend(series, start, end, metric=metric)
        lines.append(f"## {display_name(metric)}")
        if latest_fact:
            lines.append(latest_fact.text + ".")
        if month_change:
            lines.append(month_change.text)
        if year_trend:
            lines.append(year_trend.text)
        lines.append("")
    return {"data_summary.md": "\n".join(lines)}


def write_folder(folder: Path, name: str, docs: dict[str, str]) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "company.json").write_text(
        json.dumps({"company_name": name}, indent=2) + "\n", encoding="utf-8"
    )
    for filename, text in docs.items():
        (folder / filename).write_text(text, encoding="utf-8")
    print(f"write  {name}: {len(docs)} documents -> {folder}")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="Generate AI Analyst documents from the KPI data")
    parser.add_argument("--all", action="store_true",
                        help="also write a numbers-only data_summary.md for every non-fake company")
    parser.add_argument("--out", type=Path, default=REAL_DOCS_DIR,
                        help=f"folder for the --all summaries (default {REAL_DOCS_DIR}); "
                             f"fake company documents always go to {DOCS_DIR}")
    args = parser.parse_args()

    with Session(engine) as db:
        fake_names = {spec["name"] for spec in FAKE_COMPANIES}
        for company_id, name in data_access.list_companies(db):
            company = data_access.get_company(db, company_id)
            is_fake = name in fake_names and company.description == FAKE_DESCRIPTION
            # Amounts in each company's own currency (financial_records), else the config default.
            with company_currency(data_access.company_currency(db, company_id)):
                if is_fake:
                    docs, folder = WRITERS[name](Numbers(db, company_id), name), DOCS_DIR
                elif args.all:
                    docs, folder = summary_docs(db, company_id, name), args.out
                else:
                    continue
            if docs:
                write_folder(folder / slugify(name), name, docs)


if __name__ == "__main__":
    main()
