def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


# --------------------------------------------------------------------------- #
# Number helpers (all values from the DB, formatted like the analyst's facts)
# --------------------------------------------------------------------------- #

class Numbers:
    def __init__(self, db: Session, company_id: int):
        self.series = {m: data_access.get_series(db, company_id, m) for m in ("revenue", "expenses", "profit")}

    def value(self, metric: str, period: str) -> str:
        fact = value_at(self.series[metric], period, metric=metric)
        return format_value(fact.value, fact.unit)

    def change(self, metric: str, a: str, b: str) -> str:
        """'rose by 35,25,963 INR (10.2%)' / 'fell by ...' (no double signs)."""
        fact = compare_periods(self.series[metric], a, b, metric=metric)
        verb = {"up": "rose", "down": "fell", "flat": "was unchanged"}[fact.data["direction"]]
        if fact.data["direction"] == "flat":
            return verb
        amount = format_value(abs(fact.value), fact.unit)
        pct = fact.data["pct_change"]
        return f"{verb} by {amount}" + (f" ({abs(pct):.1f}%)" if pct is not None else "")

    def extreme(self, metric: str, which: str, start=None, end=None) -> tuple[str, str]:
        high, low = extremes(self.series[metric], metric=metric, start=start, end=end)
        fact = high if which == "highest" else low
        y, m = map(int, fact.period.split("-"))
        return month_label((y, m)), format_value(fact.value, fact.unit)

    def growth(self, a: str, b: str, start: str, end: str) -> tuple[str, str]:
        fact = cross_metric_growth(self.series[a], self.series[b], start, end, metric_a=a, metric_b=b)
        return f"{abs(fact.data['a']['pct_change']):.1f}%", f"{abs(fact.data['b']['pct_change']):.1f}%"


